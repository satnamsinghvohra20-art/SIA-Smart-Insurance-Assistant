def run_claim_prep_agent(claim_case_id: str) -> DraftedClaim:
    """Executes the Claim Preparation Agent."""
    start_time = time.time()
    
    facts_raw = db.get_extracted_facts(claim_case_id)
    facts = {f["key"]: f["value"] for f in facts_raw}
    eligibility = db.get_eligibility_assessment(claim_case_id) or {}
    
    patient_name = str(facts.get("patient_name", "Manpreet Kaur"))
    hospital_name = str(facts.get("hospital_name", "Apollo Speciality Hospital"))
    policy_no = str(facts.get("policy_number", "STAR-GHI-2024-9941"))
    claimed_amt = float(facts.get("total_bill_amount", 42000.0))
    
    reimb = eligibility.get("estimated_reimbursement", {})
    net_amount = float(reimb.get("maximum", 38640.0))

    db.log_audit_event(AuditEvent(
        claim_case_id=claim_case_id,
        agent_name="ClaimPrepAgent",
        event_type="EXTRACTION",
        title="Generating IRDAI Claim Package & Evidence Bundle",
        detail=f"Preparing IRDAI Form Part A/B PDF, TPA cover letter, and ready-to-dispatch hospital communication drafts.",
        severity="INFO"
    ))

    # 1. Render Official IRDAI Standard Form PDF
    pdf_path = generate_claim_form_pdf(claim_case_id, facts, eligibility)
    pdf_filename = Path(pdf_path).name

    # 2. Render TPA Cover Letter
    cover_letter = generate_cover_letter(claim_case_id, facts, eligibility)

    # 3. Draft Actionable Emails
    admission_date = facts.get("admission_date", "2026-08-10")
    discharge_date = facts.get("discharge_date", "2026-08-12")
    bill_number = facts.get("bill_number", "INV-BLR-2026-8812")

    hospital_email = {
        "email_type": "HOSPITAL_ITEMIZED_BILL_REQUEST",
        "recipient": "billing@apollohospitals.demo",
        "subject": f"Request for Itemized Pharmacy & Consumables Breakup — Patient: {patient_name} ({bill_number})",
        "body": f"""Dear Billing Team ({hospital_name}),

I was admitted to your hospital from {admission_date} to {discharge_date} under Bill No: {bill_number} (Patient: {patient_name}).

For processing my employer insurance reimbursement claim through our corporate TPA, the insurer requires an itemized pharmacy, laboratory, and OT consumable schedule with unit prices.

Could you please issue and email the itemized breakdown at your earliest convenience?

Patient Details:
- Patient Name: {patient_name}
- Invoice No: {bill_number}
- Admission: {admission_date} | Discharge: {discharge_date}

Thank you,
{patient_name}"""
    }

    tpa_email = {
        "email_type": "TPA_CLAIM_SUBMISSION",
        "recipient": "claims@starhealth.demo",
        "subject": f"Reimbursement Claim Submission — {patient_name} | Policy: {policy_no}",
        "body": f"""Dear Claims Department,

Please find attached the official IRDAI reimbursement claim submission packet for {patient_name} (Policy: {policy_no}).

Total Claimed Amount: Rs. {claimed_amt:,.2f}
Hospital: {hospital_name}
Admission: {admission_date} to {discharge_date}

Attached Documents:
1. IRDAI Standard Claim Form (Signed)
2. Final Paid Tax Invoice & Discharge Summary
3. Medical Prescriptions & Diagnostics

Kindly acknowledge receipt and provide the claim tracking reference number.

Regards,
{patient_name}"""
    }

    draft = DraftedClaim(
        claim_case_id=claim_case_id,
        form_type="IRDAI_STANDARD_REIMBURSEMENT_FORM",
        patient_name=patient_name,
        hospital_name=hospital_name,
        policy_number=policy_no,
        gross_amount=claimed_amt,
        net_eligible_amount=net_amount,
        pdf_filename=pdf_filename,
        pdf_url=f"/api/claim-cases/{claim_case_id}/claim-form-pdf",
        cover_letter_text=cover_letter,
        drafted_emails=[hospital_email, tpa_email]
    )

    db.save_drafted_claim(draft)

    # Transition claim state to READY_FOR_REVIEW
    db.update_claim_state(claim_case_id, ClaimState.READY_FOR_REVIEW)

    latency = (time.time() - start_time) * 1000
    db.record_agent_run(AgentRun(
        claim_case_id=claim_case_id,
        agent_name="ClaimPrepAgent",
        status="COMPLETED",
        latency_ms=round(latency, 2),
        tokens_consumed=410,
        confidence_score=0.99,
        summary_message=f"Generated IRDAI claim form PDF ({pdf_filename}), TPA cover letter, and 2 ready-to-dispatch email drafts.",
        tool_calls=["ReportLabPdfEngine", "CoverLetterComposer", "EmailDispatchPreparer"]
    ))

    db.log_audit_event(AuditEvent(
        claim_case_id=claim_case_id,
        agent_name="ClaimPrepAgent",
        event_type="DISPATCH",
        title="Claim Preparation Complete: Ready for Human Approval",
        detail=f"Form PDF compiled ({pdf_filename}). State transitioned to READY_FOR_REVIEW. Awaiting explicit human signature.",
        severity="SUCCESS"
    ))

    return draft
